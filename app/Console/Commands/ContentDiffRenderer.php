<?php

namespace App\Console\Commands;

use App\Content\Import\Report;

/** Renders docs/content-diff.md from an import run. */
final class ContentDiffRenderer
{
    /**
     * @param  list<array{locale: string, file: string, mapper: ?string, public: int, consumed: int, unmapped: list<\App\Content\Docx\Block>}>  $coverage
     */
    public function render(array $coverage, Report $report): string
    {
        $out = [];
        $out[] = '# Content diff and import report';
        $out[] = '';
        $out[] = 'Generated by `php artisan summit:import` from `package/docx/{en,ar,ru}` (approved copy dated 23 October 2026). Do not edit by hand; re-run the import.';
        $out[] = '';
        $out[] = 'Black DOCX runs are public copy; red runs are designer notes (see `docs/designer-notes/`). Every public block must be consumed by a mapper. Anything listed under *Unmapped public copy* is approved text the site does not use yet.';
        $out[] = '';

        // Summary table: one row per base file, columns per locale.
        $out[] = '## Coverage';
        $out[] = '';
        $out[] = '| File (EN name) | Mapper | EN | AR | RU |';
        $out[] = '|---|---|---|---|---|';
        $byPrefix = [];
        foreach ($coverage as $row) {
            $key = preg_replace('/(_EN|_RU|_Revised|_and_Content_Rules)+(?=\.docx$)/', '', $row['file']);
            $key = substr($key, 0, 6);
            $byPrefix[$key][$row['locale']] = $row;
        }
        ksort($byPrefix);
        foreach ($byPrefix as $rows) {
            $en = $rows['en'] ?? reset($rows);
            $cells = [];
            foreach (['en', 'ar', 'ru'] as $locale) {
                $r = $rows[$locale] ?? null;
                $cells[] = $r === null ? '—' : sprintf('%d/%d%s', $r['consumed'], $r['public'], $r['unmapped'] === [] ? ' ✓' : '');
            }
            $out[] = sprintf('| `%s` | %s | %s |', $en['file'], $en['mapper'] ?? '*not imported*', implode(' | ', $cells));
        }
        $out[] = '';

        $sections = [
            'label-mismatch' => ['Label mismatches', 'The same field has different approved wording in two source files. The shared component uses the master source named in each row.'],
            'reuse' => ['Approved copy reused across files', 'Copy placed on a page other than the file it comes from.'],
            'source-conflict' => ['Source conflicts', 'Facts that disagree between files or languages. Each needs a client decision.'],
            'parity' => ['Language parity', 'EN/AR/RU records whose structure differs.'],
            'note' => ['Other review notes', ''],
        ];
        foreach ($sections as $type => [$title, $intro]) {
            $entries = $report->entries($type);
            $out[] = '## '.$title;
            $out[] = '';
            if ($intro !== '') {
                $out[] = $intro;
                $out[] = '';
            }
            if ($entries === []) {
                $out[] = '_None._';
                $out[] = '';

                continue;
            }
            $out[] = '| Language | Subject | Detail |';
            $out[] = '|---|---|---|';
            foreach ($entries as $e) {
                $out[] = sprintf('| %s | %s | %s |', strtoupper($e['locale'] ?? 'all'), self::cell($e['subject']), self::cell($e['detail']));
            }
            $out[] = '';
        }

        $out[] = '## Unmapped public copy';
        $out[] = '';
        $any = false;
        foreach ($coverage as $row) {
            if ($row['unmapped'] === [] || $row['mapper'] === null) {
                continue;
            }
            $any = true;
            $out[] = sprintf('### %s / %s', strtoupper($row['locale']), $row['file']);
            $out[] = '';
            foreach ($row['unmapped'] as $b) {
                $out[] = sprintf('- `#%d` %s', $b->index, self::cell($b->text));
            }
            $out[] = '';
        }
        if (! $any) {
            $out[] = '_None. Every public block in every imported file is mapped._';
            $out[] = '';
        }

        $unclaimed = array_filter($coverage, fn ($r) => $r['mapper'] === null);
        $out[] = '## Files not imported';
        $out[] = '';
        if ($unclaimed === []) {
            $out[] = '_None._';
        } else {
            foreach ($unclaimed as $r) {
                $out[] = sprintf('- %s / `%s` (%d public blocks)', strtoupper($r['locale']), $r['file'], $r['public']);
            }
        }
        $out[] = '';

        return implode("\n", $out);
    }

    private static function cell(string $s): string
    {
        return str_replace(['|', "\n"], ['\\|', ' '], $s);
    }
}
